export function getByTopic(topic) {
  return questions.filter(q => q.topic === topic)
}

export function getContextual() {
  return questions.filter(q => q.context)
}

export function buildDiagnosticSet() {
  const byTopic = {}
  Object.values(TOPICS).forEach(t => { byTopic[t] = [] })
  questions.forEach(q => byTopic[q.topic]?.push(q))
  const set = []
  Object.values(byTopic).forEach(topicQs => {
    const picked = shuffled(topicQs).slice(0, 5)
    set.push(...picked)
  })
  return shuffled(set)
}

export function shuffled(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]]
  }
  return a
}
